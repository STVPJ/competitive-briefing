"""Wrap the briefing body into a standalone HTML page / email and a Markdown copy."""

from __future__ import annotations

import html as html_lib
from datetime import date

from markdownify import markdownify

STYLE = """\
  body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
         max-width: 700px; margin: 0 auto; padding: 20px; color: #1a1a1a; line-height: 1.6; }
  h1 { color: #1a365d; border-bottom: 2px solid #e2e8f0; padding-bottom: 8px; }
  h2 { color: #2d3748; margin-top: 24px; }
  h3 { color: #4a5568; }
  a { color: #2b6cb0; }
  ul { padding-left: 20px; }
  li { margin-bottom: 6px; }
  .date { color: #718096; }
  .footer { color: #a0aec0; font-size: 12px; margin-top: 30px; border-top: 1px solid #e2e8f0;
            padding-top: 10px; }"""


def format_date(d: date, edition: dict) -> str:
    """Edition-localised long date, from names in the config (no locale dependency)."""
    return edition["date_template"].format(
        day_name=edition["day_names"][d.weekday()], day=d.day,
        month_name=edition["month_names"][d.month - 1], year=d.year)


def wrap_html(body_html: str, edition: dict, d: date, footer: str = "Generated by competitive-briefing") -> str:
    title = html_lib.escape(edition["title"])
    return f"""<!DOCTYPE html>
<html lang="{html_lib.escape(edition['html_lang'])}">
<head>
<meta charset="utf-8">
<title>{title} — {d.isoformat()}</title>
<style>
{STYLE}
</style>
</head>
<body>
<h1>{title}</h1>
<p class="date">{html_lib.escape(format_date(d, edition))}</p>
{body_html}
<div class="footer">{html_lib.escape(footer)}</div>
</body>
</html>
"""


def to_markdown(body_html: str, edition: dict, d: date) -> str:
    body = markdownify(body_html, heading_style="ATX").strip()
    return f"# {edition['title']}\n\n*{format_date(d, edition)}*\n\n{body}\n"
